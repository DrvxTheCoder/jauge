// Generates lib/correction/default-table.ts from the built-in CSV table.
// Usage: npm run gen:table
// The output is committed; tests/correction.test.ts checks it stays in sync with the CSV.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "lib/data/correction/butane-standard-15-36.csv");
const out = join(root, "lib/correction/default-table.ts");

const NUM = /^[-+]?\d+(\.\d+)?$/;
const lines = readFileSync(src, "utf8").replace(/^﻿/, "").split(/\r?\n/);
const header = lines[0].split(",").map((h) => h.trim());
const expected = ["temperature", "liquid_correction", "gas_coefficient"];
if (header.join() !== expected.join()) throw new Error(`Unexpected header: ${lines[0]}`);

const rows = [];
lines.slice(1).forEach((line, i) => {
  if (!line.trim()) return;
  const cells = line.split(",").map((c) => c.trim());
  if (cells.length !== 3 || !cells.every((c) => NUM.test(c))) throw new Error(`Line ${i + 2}: ${line}`);
  // Keep the CSV text as written so the TS literal is exactly the table value.
  rows.push(`  { t: ${cells[0]}, liquid: ${cells[1]}, gas: ${cells[2]} },`);
});

const body = `// GENERATED by scripts/gen-default-table.mjs from ${relative(root, src).replace(/\\/g, "/")}. Do not edit by hand.
import type { CorrectionRow } from "../types";

export const DEFAULT_TABLE_ROWS: readonly CorrectionRow[] = [
${rows.join("\n")}
];
`;
writeFileSync(out, body);
console.log(`Wrote ${rows.length} rows to ${relative(root, out)}`);
